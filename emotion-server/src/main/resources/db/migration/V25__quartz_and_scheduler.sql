-- ============ 人维护的任务定义表 ============
-- 新增任务 = 写一个实现 ManagedTask 的 Spring bean + 往这里插一行（推荐走下一个迁移版本，
-- 这样多台/多环境排班一致，不必各自手工 INSERT）。
-- bean_name 是 Spring 容器里的 bean 名；写错的话运行时会直接 NoSuchBeanDefinition 并记一条失败留痕。
CREATE TABLE IF NOT EXISTS t_scheduler_job (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    job_name VARCHAR(64) NOT NULL COMMENT '任务名，Quartz JobKey 用的就是它；改名等于重建任务',
    job_group VARCHAR(64) NOT NULL DEFAULT 'DEFAULT' COMMENT '分组，暂按 DEFAULT 单组跑',
    bean_name VARCHAR(128) NOT NULL COMMENT '执行体：容器中实现了 ManagedTask 的 bean 名',
    cron_expr VARCHAR(64) NOT NULL COMMENT 'Quartz cron（含秒位），一律按 Asia/Shanghai 解释，例如 0 0 19 * * ?',
    misfire_policy VARCHAR(16) NOT NULL DEFAULT 'DO_NOTHING' COMMENT '错过触发时的处置：DO_NOTHING=放过这次 / FIRE_ONCE_NOW=补跑一次',
    enabled TINYINT NOT NULL DEFAULT 1 COMMENT '1=启用，0=停用（停用会连同 Quartz 里的触发器一起摘掉）',
    description VARCHAR(200) DEFAULT NULL COMMENT '给人看的一句话说明',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_job_name (job_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='定时任务定义(改这张表即改排班)';

-- ============ 执行留痕表 ============
-- 失败原因/跳过理由这类「人话」只有这里存。QRTZ_* 只负责调度本身，凑不出这些。
CREATE TABLE IF NOT EXISTS t_scheduler_run (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    job_name VARCHAR(64) NOT NULL COMMENT '对应 t_scheduler_job.job_name',
    source VARCHAR(12) NOT NULL DEFAULT 'SCHEDULE' COMMENT 'SCHEDULE=定时到点 / MANUAL=手工点了一次',
    status VARCHAR(12) NOT NULL COMMENT 'SUCCESS/FAILED/SKIPPED',
    message VARCHAR(1000) DEFAULT NULL COMMENT '结果摘要或异常原因，中文，给人看',
    started_at DATETIME NOT NULL,
    finished_at DATETIME DEFAULT NULL,
    duration_ms BIGINT DEFAULT NULL COMMENT '耗时毫秒',
    INDEX idx_job_started (job_name, started_at),
    INDEX idx_status_started (status, started_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='定时任务执行留痕';


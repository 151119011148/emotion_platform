-- Flyway migration V25: 单机定时任务平台（Quartz + JDBC 持久化）
-- -----------------------------------------------------------------------------
-- 为什么表在这里建、不让 Spring Boot 自己建：
--   spring.quartz.jdbc.initialize-schema=never（application.yml）已经把路径关掉了。
--   两条路径同时建 QRTZ_* 表，谁先谁后都会踩到对方；所有 SQL 一律由 Flyway 收口。
-- 三个层次：
--   QRTZ_*          Quartz 自己的调度账（触发器状态、下一火时间、实例心跳）。不要手改。
--   t_scheduler_job 人维护的任务定义：挂哪个 Spring bean、cron、启不启用。改这张表即改排班。
--   t_scheduler_run 每次执行的留痕：人工看得懂的结果、失败原因、耗时。Quartz 的账凑不出这些。
-- Quartz 官方 MySQL InnoDB DDL（quartz-scheduler/quartz，绝对路径 org/quartz/impl/jdbcjobstore/
--   tables_mysql_innodb.sql），这里去掉了开头的 DROP（删库级别，绝不能混在迁移里）与末尾 commit
--   （Spring 自己管事务），其余逐字照搬。
-- -----------------------------------------------------------------------------


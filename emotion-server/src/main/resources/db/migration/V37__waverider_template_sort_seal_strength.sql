-- ============================================================================
-- V37 · WaveRider：把模板的默认排序从「可执行性升序」改为「封单强度降序」
--
-- 背景：V35 建的三个模板种子里 sort_by 都是 "executability"（封单比升序），
--       那套口径把「封单锁死」当成可执行性折价，越强越往后排甚至剔除。
--
-- 依据（226 个样本按 封单额 ÷ 成交额 分五档，两种买入口径并排算）：
--       档位       n     A 口径(T日涨停价打板)      B 口径(D+1 开盘买入)
--       < 15%    100        +1.71%  胜53.0%           +0.38%  胜47.0%
--       15~50%    58        +3.55%  胜69.0%           -0.30%  胜39.7%
--       50~150%   21        +4.37%  胜71.4%           -0.24%  胜47.6%
--       150~300%  17        +5.40%  胜82.4%           -1.41%  胜29.4%
--       >= 300%   23        +7.56%  胜87.0%           -1.71%  胜 8.7%
--   A 口径严格单调递增，B 口径严格单调递减 → 封单强度是「本策略真实买点」下的
--   正向因子，「买不进」只在「D+1 才买」的前提下成立，而那不是本策略的执行方式。
--
-- 幂等：改成 seal_strength 之后，WHERE 与 REPLACE 都匹配不到，重放为空操作。
-- 注：config_json 是 LONGTEXT（不是 JSON 列），所以直接做字符串替换。
--     已存在的 t_strategy_version 快照**有意不动**——版本快照应保持内容不可变，
--     需要新排序的旧策略请「按模板重建」或「另存为新版本」。
-- ============================================================================

UPDATE t_strategy_template
SET config_json = REPLACE(config_json, '"sort_by":"executability"', '"sort_by":"seal_strength"')
WHERE config_json LIKE '%"sort_by":"executability"%';

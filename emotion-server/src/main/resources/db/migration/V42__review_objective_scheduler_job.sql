-- Flyway migration V42: 每日复盘「客观数据录入」的排班
-- -----------------------------------------------------------------------------
-- 干什么：每交易日 19:30 把复盘页那两步（一键拉取行情 → 保存复盘）里的客观部分做掉——
--   ① 跑 T1–T7，公开原始数据落库（三池明细 / 五大指数 / 全市场统计 / 行业快照 / 档位溢价 / 监管）；
--   ② 给每个「写过复盘」的账号补当天一行 t_daily_record，只带客观九数与引擎算出来的派生列
--      （五维分 / 温度 / 阶段带 / 方向 / 信号）；当天已有行就只重算派生列。
--
-- 绝不干什么：十三项主观字段（主线、龙头、龙二、轮动笔记、复盘笔记、明日计划、我的仓位、
--   题材评分、九个 manual_* 覆盖列）与持仓台账 t_position 一个字都不写。
--   持仓与盘面判断归他人工维护，机器代填等于把「没判断」伪装成「判断过了」，
--   而这两者在页面上长得一样。改判过的阶段带（stage_overridden=1）也保住，机器的阶段带盖不上去。
--
-- 为什么是 19:30：19:00 的 daily_market_pull 打的是同一个上游快照，错开半小时避免两次拉取叠在一起，
--   也让三池先落好——执行体拿它当建行的前置闸（明细为空就不建行，宁可不写也不写空壳）。
--
-- 名单口径：只给 t_daily_record 里已有的 user_id 建行，不给一个从没复盘过的账号凭空造行。
--
-- misfire 用 DO_NOTHING：深夜补跑一次拉到的还是那天收盘后的数（无害但无用），
--   而次日 T1 自己会回补 T-1/T-2 的涨停池，漏跑不丢结论。
-- INSERT IGNORE：重放迁移不覆盖运维手工改过的 cron / 停用状态。
-- -----------------------------------------------------------------------------
